#!/usr/bin/env python3

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SPX_HEADER = ROOT / "godot_modules/spx/gdextension_spx_ext.h"
SPX_SOURCE = ROOT / "godot_modules/spx/gdextension_spx_ext.cpp"
OUTPUT_HEADER = ROOT / "gdexample/src/spx_api.h"
OUTPUT_SOURCE = ROOT / "gdexample/src/spx_api.cpp"


def type_name(function_name: str) -> str:
	parts = function_name.removeprefix("spx_").split("_")
	return "GDExtensionSpx" + "".join(part[:1].upper() + part[1:] for part in parts)


def extract_abi_declarations(header: str) -> str:
	start_marker = "typedef struct {\n\tint32_t size;"
	start = header.index(start_marker)
	end = header.index("\n\n#ifdef __cplusplus", start)
	lines = header[start:end].splitlines()

	# The engine header currently contains one repeated typedef. Keep the client
	# header clean while preserving declaration order.
	seen_typedefs: set[str] = set()
	result: list[str] = []
	for line in lines:
		if line.startswith("typedef void (*"):
			if line in seen_typedefs:
				continue
			seen_typedefs.add(line)
		result.append(line.rstrip())
	return "\n".join(result).rstrip()


def extract_registered_functions(source: str) -> list[str]:
	return re.findall(r"REGISTER_SPX_INTERFACE_FUNC\((spx_[a-z0-9_]+)\);", source)


def grouped_lines(functions: list[str], render) -> list[str]:
	lines: list[str] = []
	last_group = None
	for function_name in functions:
		group = function_name.split("_")[1]
		if group != last_group:
			if last_group is not None:
				lines.append("")
			lines.append(f"\t// {group.capitalize()}")
			last_group = group
		lines.append(render(function_name))
	return lines


def generate_header(abi_declarations: str, functions: list[str]) -> str:
	fields = grouped_lines(
		functions,
		lambda name: f"\t{type_name(name)} {name.removeprefix('spx_')} = nullptr;",
	)
	return "\n".join(
		[
			"// Generated by tools/generate_spx_api.py. Do not edit manually.",
			"#pragma once",
			"",
			"#include <cstdint>",
			"",
			"#include <gdextension_interface.h>",
			"",
			"namespace spx_api {",
			"",
			'extern "C" {',
			"",
			"typedef GDExtensionConstStringPtr GdString;",
			"typedef GDExtensionInt GdInt;",
			"typedef GDExtensionInt GdObj;",
			"typedef GDExtensionBool GdBool;",
			"typedef float GdFloat;",
			"typedef GdObj ObjectId;",
			"",
			"typedef struct {",
			"\tGdFloat x;",
			"\tGdFloat y;",
			"\tGdFloat z;",
			"\tGdFloat w;",
			"} GdVec4;",
			"",
			"typedef struct {",
			"\tGdFloat x;",
			"\tGdFloat y;",
			"\tGdFloat z;",
			"} GdVec3;",
			"",
			"typedef struct {",
			"\tGdFloat x;",
			"\tGdFloat y;",
			"} GdVec2;",
			"",
			"typedef GdVec2 Vector2;",
			"",
			"typedef struct {",
			"\tGdFloat r;",
			"\tGdFloat g;",
			"\tGdFloat b;",
			"\tGdFloat a;",
			"} GdColor;",
			"",
			"typedef struct {",
			"\tGdVec2 position;",
			"\tGdVec2 size;",
			"} GdRect2;",
			"",
			abi_declarations,
			"",
			'} // extern "C"',
			"",
			"struct GDExtensionInterface {",
			"\tGDExtensionInterfaceGetProcAddress get_proc_address = nullptr;",
			"",
			*fields,
			"",
			"\tstatic GDExtensionInterface &get_instance() {",
			"\t\tstatic GDExtensionInterface instance;",
			"\t\treturn instance;",
			"\t}",
			"",
			"\toperator bool() const {",
			"\t\treturn is_available();",
			"\t}",
			"",
			"\tvoid initialize(GDExtensionInterfaceGetProcAddress p_get_proc_address);",
			"",
			"private:",
			"\tbool is_available() const {",
			"\t\treturn isInitialized;",
			"\t}",
			"",
			"\ttemplate <typename T>",
			"\tT resolve(const char *p_name) const {",
			"\t\treturn get_proc_address != nullptr",
			"\t\t\t\t? reinterpret_cast<T>(get_proc_address(p_name))",
			"\t\t\t\t: nullptr;",
			"\t}",
			"",
			"\tbool isInitialized = false;",
			"};",
			"",
			"} // namespace spx_api",
			"",
		]
	)


def generate_source(functions: list[str]) -> str:
	resolvers = grouped_lines(
		functions,
		lambda name: (
			f"\t{name.removeprefix('spx_')} = "
			f"resolve<{type_name(name)}>(\"{name}\");"
		),
	)
	availability = [
		f"\t\t\t{name.removeprefix('spx_')} != nullptr" for name in functions
	]
	for index in range(len(availability) - 1):
		availability[index] += " &&"
	availability[-1] += ";"

	return "\n".join(
		[
			"// Generated by tools/generate_spx_api.py. Do not edit manually.",
			'#include "spx_api.h"',
			"",
			"namespace spx_api {",
			"",
			"void GDExtensionInterface::initialize(",
			"\t\tGDExtensionInterfaceGetProcAddress p_get_proc_address) {",
			"\tget_proc_address = p_get_proc_address;",
			"",
			*resolvers,
			"",
			"\tisInitialized = get_proc_address != nullptr &&",
			*availability,
			"}",
			"",
			"} // namespace spx_api",
			"",
		]
	)


def main() -> None:
	header = SPX_HEADER.read_text(encoding="utf-8")
	source = SPX_SOURCE.read_text(encoding="utf-8")
	abi_declarations = extract_abi_declarations(header)
	functions = extract_registered_functions(source)

	if not functions:
		raise RuntimeError("No registered SPX functions found")

	missing_types = [name for name in functions if f"(*{type_name(name)})" not in header]
	if missing_types:
		raise RuntimeError(f"Missing function pointer typedefs: {missing_types}")

	OUTPUT_HEADER.write_text(generate_header(abi_declarations, functions), encoding="utf-8")
	OUTPUT_SOURCE.write_text(generate_source(functions), encoding="utf-8")
	print(f"Generated {len(functions)} SPX interface bindings")


if __name__ == "__main__":
	main()
